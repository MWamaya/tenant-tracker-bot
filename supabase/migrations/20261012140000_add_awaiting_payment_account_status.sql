-- New account_status: 'awaiting_payment'. Sits between 'pending' (just
-- signed up, nothing set up yet, blocked from the whole app) and 'active'
-- (fully unlocked). An admin-activated landlord lands here: they can set
-- up M-Pesa/bank email forwarding in Settings right away, but every other
-- page is still gated until they actually pay (which flips them straight
-- to 'active', same as it always has).
ALTER TABLE public.profiles DROP CONSTRAINT profiles_account_status_check;
ALTER TABLE public.profiles ADD CONSTRAINT profiles_account_status_check
  CHECK (account_status = ANY (ARRAY['active'::text, 'suspended'::text, 'expired'::text, 'pending'::text, 'awaiting_payment'::text]));

-- Both triggers below previously only reacted to a transition INTO
-- 'active'. They now react to a transition into EITHER 'active' or
-- 'awaiting_payment' — the two statuses where real access starts — since
-- the forwarding address and the activation email should land the moment
-- a landlord can actually use the app, not only once they've paid.
--
-- Guard against double-firing on the later awaiting_payment -> active
-- payment transition: the condition only fires when OLD was NOT already
-- in the "has access" set, so once a landlord is at awaiting_payment,
-- paying and moving to active does not re-fire either trigger.
CREATE OR REPLACE FUNCTION public.generate_inbound_email()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER SET search_path = public
AS $$
DECLARE
  base_slug TEXT;
  candidate TEXT;
  suffix INT := 1;
BEGIN
  base_slug := lower(regexp_replace(coalesce(NEW.full_name, ''), '[^a-zA-Z0-9\s]', '', 'g'));
  base_slug := regexp_replace(trim(base_slug), '\s+', '.', 'g');

  IF base_slug = '' THEN
    base_slug := 'landlord';
  END IF;

  candidate := base_slug || '@kodipap.com';

  WHILE EXISTS (SELECT 1 FROM public.profiles WHERE inbound_email = candidate) LOOP
    suffix := suffix + 1;
    candidate := base_slug || suffix::text || '@kodipap.com';
  END LOOP;

  NEW.inbound_email := candidate;
  PERFORM set_config('app.inbound_email_autogenerated', 'true', true);
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS generate_inbound_email_trigger ON public.profiles;
CREATE TRIGGER generate_inbound_email_trigger
BEFORE UPDATE ON public.profiles
FOR EACH ROW
WHEN (
  OLD.account_status NOT IN ('active', 'awaiting_payment')
  AND NEW.account_status IN ('active', 'awaiting_payment')
  AND NEW.inbound_email IS NULL
)
EXECUTE FUNCTION public.generate_inbound_email();

DROP TRIGGER IF EXISTS notify_landlord_activation_trigger ON public.profiles;
CREATE TRIGGER notify_landlord_activation_trigger
AFTER UPDATE ON public.profiles
FOR EACH ROW
WHEN (
  OLD.account_status NOT IN ('active', 'awaiting_payment')
  AND NEW.account_status IN ('active', 'awaiting_payment')
  AND NEW.inbound_email IS NOT NULL
)
EXECUTE FUNCTION public.notify_landlord_activation();
